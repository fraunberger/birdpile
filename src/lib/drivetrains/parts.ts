// Mountain bike 1x12 drivetrain parts: Shimano and SRAM, mid-tier and up.
//
// Every weight carries where it came from. The manufacturer's own number is
// preferred; when Shimano or SRAM didn't publish one, the figure is a launch
// claim reported by the press, and failing that an independent scale weight.
// `kind` says which, so the page can show it.
//
// Weights are what the source says, at the basis the source says (crank
// length, chainring, chain links, battery or not). `adjust` corrects the few
// figures whose basis differs enough to skew a total, such as a derailleur
// quoted without its battery, and says why. Totals use stated + adjust.
//
// Prices are US list prices where one was published, otherwise a regular
// (not sale) price at a US shop. `kind: "estimate"` marks the few prices no
// listing was found for. Every price can be overridden on the page.

export type Brand = "SRAM" | "Shimano";
export type Slot = "shifter" | "derailleur" | "cassette" | "chain" | "crankset";

// Parts that work together. SRAM's T-Type parts mix freely across XX SL, XX,
// X0, GX and Eagle 90; Shimano's 12-speed Hyperglide+ parts mix across XTR,
// XT, SLX and Deore. The two brands don't mix here.
export type System = "sram-t-type" | "shimano-12";

// What a shifter sends and what a derailleur listens for.
export type Actuation = "sram-axs" | "sram-mech" | "shimano-mech" | "shimano-di2";

export type WeightSourceKind = "manufacturer" | "claimed" | "measured" | "retailer";
export type PriceSourceKind = "msrp" | "retail" | "estimate";

export interface WeightSource {
  kind: WeightSourceKind;
  label: string;
  url: string;
}

export interface PriceSource {
  kind: PriceSourceKind;
  label: string;
  url: string;
}

export interface Part {
  id: string;
  brand: Brand;
  system: System;
  slot: Slot;
  tier: string; // the group the part belongs to, e.g. "XT" or "X0"
  name: string;
  model: string;
  grams: number; // as stated by the source
  basis: string; // what the stated weight includes
  adjust?: { grams: number; why: string; source?: WeightSource };
  weightSource: WeightSource;
  price: number; // USD
  priceNote?: string;
  priceSource: PriceSource;
  actuation?: Actuation; // shifters and derailleurs only
  // Cranks only: whether a 165mm arm is sold, and where that's stated.
  offers165?: { ok: boolean; url: string; label: string };
  notes?: string;
}

